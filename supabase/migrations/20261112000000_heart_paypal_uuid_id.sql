-- Migration 13: paypal_subscriptions.id text -> uuid (Nov 10, 2026).
--
-- DEFECT (found by the Nov 10, 2026 sandbox end-to-end test): migration
-- 11 created paypal_subscriptions.id as text, but the app model binds
-- it as a real uuid (app/models.py UuidString — the same Nov 9 lesson
-- as mint_invite/signup: Postgres has no implicit text = uuid
-- operator). Postgres accepts the INSERT (assignment cast uuid ->
-- text) but every later statement that compares the PK fails with
-- sqlalchemy.exc.ProgrammingError "operator does not exist:
-- text = uuid" (WHERE paypal_subscriptions.id = $1::UUID):
--   - POST /paypal/subscribe: db.commit() succeeds, then building the
--     response re-reads the expired row by PK -> 500, so the caller
--     never gets the approval_url even though the row (and the PayPal
--     subscription) exist.
--   - POST /paypal/webhooks BILLING.SUBSCRIPTION.ACTIVATED: the UPDATE
--     that flips the row ACTIVE fails at db.commit() -> 500, so
--     premium NEVER activates. The route turns the exception into an
--     HTTPException 500, which FastAPI returns without logging a
--     Python traceback — that is why the deliveries 500'd repeatedly
--     with nothing in the log. (A SALE.COMPLETED delivery still wrote
--     its 500c/499c payout rows: process_payouts_for_invoice commits
--     them before the handler's final commit fails on the row update.)
-- The fix is at the DB layer, not the model: every other id column in
-- the app is uuid in Postgres and UuidString in the model (see
-- models.py UuidString docstring); migration 11 was the outlier.
-- This alter keeps every existing row: all ids were generated by the
-- app's new_uuid() (valid UUID strings), so id::uuid casts cleanly —
-- including the leftover APPROVAL_PENDING subscription from the Nov 10
-- sandbox test (I-93KW6Y1P7NGR): its local row is untouched except
-- for the column type, and the subscription itself is not modified.
-- Safe to apply with the app stopped (same rule as migration 5); the
-- table is tiny, the rewrite is instant.
--
-- LATENT, SAME DEFECT CLASS (not fixed here — separate follow-up):
-- subscriptions, invoice_records, payouts and crypto_payments also
-- declare `id text primary key` in migrations 8 while their models
-- bind UuidString. They have not 500'd yet only because no production
-- flow has done a PK UPDATE/lookup on them (Stripe's _sync_subscription
-- does update an existing row by PK, so the first subscription.updated
-- webhook for an existing Stripe subscription would hit it).

alter table paypal_subscriptions alter column id type uuid using id::uuid;

comment on column paypal_subscriptions.id is 'Local row id (uuid, app-generated) — must stay uuid: the model binds it as a real uuid and Postgres has no text = uuid operator (Nov 10, 2026 fix).';
