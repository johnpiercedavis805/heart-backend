-- HeArt — invented by John Davis.
-- Migration 14: subscriptions / invoice_records / payouts /
-- crypto_payments id text -> uuid (Nov 10, 2026).
--
-- DEFECT (same class as migration 13, which fixed
-- paypal_subscriptions): migrations 6–8 created these four tables
-- with `id text primary key`, but every model binds id as a real uuid
-- (app/models.py UuidString). Postgres accepts the INSERT (assignment
-- cast uuid -> text) but every later statement that compares the PK
-- fails with sqlalchemy.exc.ProgrammingError "operator does not
-- exist: text = uuid" (WHERE <table>.id = $1::UUID). The failure
-- needs no explicit PK lookup — the ORM's dirty-row flush on commit
-- issues the UPDATE by PK, so any webhook that mutates a loaded row
-- 500s:
--   - subscriptions: _sync_subscription (billing.py) updates the row
--     on customer.subscription.updated, and _sync_invoice's
--     belt-and-braces activation flips it active — the first
--     subscription.updated for an existing Stripe subscription
--     would have hit it.
--   - invoice_records: _sync_invoice updates the row on a second
--     delivery for the same invoice; _sync_refund / _sync_credit_note
--     update it on charge.refunded / credit_note.created.
--   - payouts: _retry_payout_rows updates failed/held rows on the
--     POST /billing/connect/payouts re-run (failed -> transferred).
--   - crypto_payments: handle_coinbase_webhook updates the row on
--     charge:confirmed / charge:failed / charge:pending, and
--     _confirm_charge sets status + premium_until before the commit.
--
-- WHY THE FIX IS AT THE DB LAYER FOR ALL FOUR (not the model): the
-- investigation found no table stores external provider ids in its
-- PK. Every id is app-generated by new_uuid() — no creation site in
-- billing.py, coinbase.py or paypal.py ever passes id= (verified by
-- grep, Nov 10, 2026). The provider ids live in their own text
-- columns, untouched by this migration:
--   - subscriptions.stripe_subscription_id  (sub_...)
--   - invoice_records.stripe_invoice_id     (in_..., paypal:<sale id>,
--                                             coinbase:<charge id>)
--   - payouts.stripe_invoice_id / stripe_subscription_id (text refs)
--   - crypto_payments.coinbase_charge_id    (Coinbase charge id)
-- There is no FK pointing at any of these four PKs, and no migration
-- after 6–8 touches them, so the alter is a plain column-type change.
-- This keeps every existing row: all ids are valid UUID strings, so
-- id::uuid casts cleanly — including the live smoke-test rows from
-- Nov 9 (subscription sub_1UZvlz2OeCOdPBLAwYZS1oam, invoice
-- in_1UZvly2OeCOdPBLAFGej4d1I and their 500c/499c payout rows).
--
-- BEFORE APPLYING TO RENDER, run this pre-check against the live DB
-- (it must return zero rows — any non-UUID id would abort the alter):
--   select 'subscriptions' as t, id from subscriptions
--     where id !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
--   union all select 'invoice_records', id from invoice_records
--     where id !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
--   union all select 'payouts', id from payouts
--     where id !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
--   union all select 'crypto_payments', id from crypto_payments
--     where id !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$';
-- Safe to apply with the app stopped (same rule as migration 5); the
-- tables are tiny, the rewrites are instant. Pinned by tests in
-- api/tests/test_stripe.py (subscriptions, invoice_records, payouts)
-- and api/tests/test_crypto.py (crypto_payments).

alter table subscriptions alter column id type uuid using id::uuid;
alter table invoice_records alter column id type uuid using id::uuid;
alter table payouts alter column id type uuid using id::uuid;
alter table crypto_payments alter column id type uuid using id::uuid;

